template <size_t N>
inline double polarDb (const PolarRow (&p)[N], double f, double angleDeg)
{
    angleDeg = std::clamp (angleDeg, 0.0, 90.0);
    auto at = [&] (const PolarRow& r)
    {
        const double a[4] = { 0.0, r.a30, r.a60, r.a90 };
        const double x = angleDeg / 30.0;
        const int i = std::min (2, (int) x);
        return a[i] + (x - i) * (a[i + 1] - a[i]);
    };
    if (f <= p[0].f) return at (p[0]);
    if (f >= p[N - 1].f) return at (p[N - 1]);
    size_t i = 0;
    while (i + 1 < N && p[i + 1].f < f) ++i;
    const double u = std::log (f / p[i].f) / std::log (p[i + 1].f / p[i].f);
    return at (p[i]) + u * (at (p[i + 1]) - at (p[i]));
}

// Efeito de proximidade de cardioide (forma física 1ª ordem), limitado a +10 dB como na ficha:
// a 6 mm dá ~+6,6 dB em 100 Hz e ~+8,7 dB em 50 Hz.
inline double proximityDb (double f, double distMm)
{
    const double f0 = 230.0 * 6.0 / distMm;
    const double raw = 10.0 * std::log10 (1.0 + (f0 / f) * (f0 / f));
    return 10.0 * std::tanh (raw / 10.0);
}

// Resposta completa do microfone (dB) na frequência f
inline double responseDb (const Settings& s, double f)
{
    double db = 0.0;
    if (s.model == SM7B)
    {
        db = lookup (sm7bCurve, f, 6.0, 24.0);
        if (s.bassCut) db += lookup (sm7bBassCutDelta, f, 6.0, 0.0) * (f > 500.0 ? 0.0 : 1.0);
        if (s.presence) db += (f < 700.0 ? 0.0 : lookup (sm7bPresenceDelta, f, 0.0, 0.0) * (f > 13000.0 ? 0.0 : 1.0));
        db += polarDb (sm7bPolar, f, s.angle);
    }
    else if (s.model == MD421)
    {
        db = lookup (md421Curve, f, 12.0, 24.0);
        db += md421BassDipDb (s.md421Bass, f);
        db += polarDb (md421Polar, f, s.angle);
    }
    else
    {
        db = lookup (sm57Curve, f, 6.0, 24.0);
        db += polarDb (sm57Polar, f, s.angle);
    }
    db += proximityDb (f, distanceMm (s.distance));
    db += sensitivityDb (s.model);
    return db;
}
