inline double md421BassDipDb (int pos, double f)
{
    if (pos <= 0) return 0.0;
    const float* d = md421BassDips[std::min (pos, 4) - 1];
    const int n = 13;
    if (f <= md421BassFreqs[0]) return d[0];
    if (f >= md421BassFreqs[n - 1]) return d[n - 1];
    int i = 0;
    while (i + 1 < n && md421BassFreqs[i + 1] < f) ++i;
    const double u = std::log (f / md421BassFreqs[i]) / std::log ((double) md421BassFreqs[i + 1] / md421BassFreqs[i]);
    return d[i] + u * (d[i + 1] - d[i]);
}

template <size_t N>
inline double lookup (const float (&t)[N][2], double f, double belowSlopeDbPerOct, double aboveSlopeDbPerOct)
{
    if (f <= t[0][0]) return t[0][1] - belowSlopeDbPerOct * std::log2 (t[0][0] / std::max (f, 1.0));
    if (f >= t[N - 1][0]) return t[N - 1][1] - aboveSlopeDbPerOct * std::log2 (f / t[N - 1][0]);
    size_t i = 0;
    while (i + 1 < N && t[i + 1][0] < f) ++i;
    const double l0 = std::log ((double) t[i][0]), l1 = std::log ((double) t[i + 1][0]);
    const double u = (std::log (f) - l0) / (l1 - l0);
    return t[i][1] + u * (t[i + 1][1] - t[i][1]);
}

